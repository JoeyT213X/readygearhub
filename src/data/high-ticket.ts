export function highTicketToCatalogItem(item: HighTicketItem): CatalogItem {
  const official = item.fallbackUrl;
  const manual = (item.affiliateUrl && item.affiliateUrl.trim()) || '';
  const programId = programIdForItem(item.id);
  const out = manual
    ? { href: manual, affiliate: true, programId }
    : resolveOutbound(programId, official, item.id);
  return {
    id: item.id,
    title: item.title,
    blurb: item.blurb,
    sourceName: item.sourceName,
    href: out.href,
    rel: out.affiliate ? 'sponsored nofollow noopener' : 'noopener',
    affiliate: out.affiliate,
    hideOnPaid: isNoPpcProgram(out.programId || programId),
    programId: out.programId || programId,
    category: item.category,
    alsoIn: item.alsoIn,
    image: item.image,
    imageKind: item.imageKind,
    priceLabel: item.price && item.price !== 'See price' ? item.price : 'Price on official site',
    offerLabel: item.offerLabel || 'Official site',
    ctaLabel: item.cta || 'Check listing',
    ctaKind: item.ctaKind,
    groups: item.groups,
    kind: 'brand',
    origin: 'directory',
    filler: item.filler,
    usBadge: item.us || undefined,
    storeLevel: isStoreFront(official) || undefined,
  };
}

export function highTicketCatalogItems(): CatalogItem[] {
  return highTicketItems.map(highTicketToCatalogItem);
}
